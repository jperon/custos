local loader = assert(loadfile("tests/helpers/mini_busted.lua"))
local mini = loader()
return describe("mini_busted — échecs de hooks", function()
  after_each(function()
    return mini.reset()
  end)
  it("un setup en échec fait échouer la suite (code retour 1)", function()
    mini.reset()
    mini.describe("bloc", function()
      mini.setup(function()
        return error("fixture absente")
      end)
      return mini.it("test vert", function()
        return assert.is_true(true)
      end)
    end)
    return assert.equals(1, mini.run())
  end)
  it("un before_each en échec fait échouer la suite (code retour 1)", function()
    mini.reset()
    mini.describe("bloc", function()
      mini.before_each(function()
        return error("hook cassé")
      end)
      return mini.it("test vert", function()
        return assert.is_true(true)
      end)
    end)
    return assert.equals(1, mini.run())
  end)
  return it("un after_each en échec fait échouer la suite (code retour 1)", function()
    mini.reset()
    mini.describe("bloc", function()
      mini.after_each(function()
        return error("hook cassé")
      end)
      return mini.it("test vert", function()
        return assert.is_true(true)
      end)
    end)
    return assert.equals(1, mini.run())
  end)
end)
