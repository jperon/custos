local util = require("ipparse.lib.util")
local test
test = util.test
local sp = require("ipparse.lib.pack_compat").pack
local su = require("ipparse.lib.pack_compat").unpack
local ip6 = require("ipparse.l3.ip6")
local ip = require("ipparse.l3.ip")
local dns = require("ipparse.l7.dns")
local quic = require("ipparse.l4.quic")
local frames = require("ipparse.l4.quic.frames")
test("ip6: truncated header returns nil", function()
  local res, off = ip6.parse("\096\000\000\000", 1)
  return assert(res == nil and off == 1, "truncated IPv6 header should return nil")
end)
test("ip: get_version out of bounds returns nil", function()
  assert(ip.get_version("", 1) == nil, "empty buffer")
  return assert(ip.get_version("\069", 5) == nil, "offset past end")
end)
test("ip: parse empty buffer returns nil, err", function()
  local res, err = ip.parse("", 1)
  return assert(res == nil and err, "should return nil plus an error message")
end)
test("quic: parse empty buffer returns nil", function()
  local q, off = quic.parse("", 1)
  return assert(q == nil and off == 1, "empty payload should return nil")
end)
test("quic: truncated long header returns nil", function()
  local q, off = quic.parse("\192\000", 1)
  return assert(q == nil, "truncated long header should return nil")
end)
test("quic: ACK frame with huge range count is rejected", function()
  local raw = "\002\000\000" .. "\191\255\255\255" .. "\000"
  local frame, _, err = frames.parse_frame(raw, 1)
  return assert(frame == nil and err and err:match("too large"), "expected range-count rejection, got " .. tostring(err))
end)
test("quic: validate_frames detects truncated CRYPTO frame", function()
  local raw = "\006\000\064\100"
  local ok, err = frames.validate_frames(raw)
  return assert(ok == false and err, "truncated CRYPTO should fail validation")
end)
test("dns: circular compression pointer is rejected", function()
  local hdr = sp(">HHHHHH", 0x1234, 0x0100, 1, 0, 0, 0)
  local name = "\192\012"
  local qd = name .. sp(">HH", 1, 1)
  local msg = hdr .. qd
  local res, _, err = dns.parse(msg, 1)
  assert(res == nil or err or (res and res.questions == nil) or true)
  local lbls, lerr
  lbls, _, lerr = dns.labels(msg, 13, 1)
  return assert(lbls == nil and lerr and lerr:match("loop"), "expected pointer-loop error, got " .. tostring(lerr))
end)
test("dns: truncated label returns error", function()
  local lbls, _, err = dns.labels("\010ab", 1, 1)
  return assert(lbls == nil and err, "truncated label should return an error")
end)
test("pack_compat: unpack on short data raises a clear error", function()
  local ok, err = pcall(su, ">I4", "\001\002", 1)
  return assert(not ok and tostring(err):match("too short"), "expected 'data string too short', got " .. tostring(err))
end)
return util.summary("malformed")
