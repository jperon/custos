local util = require("ipparse.lib.util")
local test
test = util.test
local dns = require("ipparse.l7.dns")
local hex2bin
hex2bin = require("ipparse.init").hex2bin
local dns_query = hex2bin("123401000001000000000000076578616d706c6503636f6d0000010001")
local dns_response = hex2bin("123481800001000100000000" .. "076578616d706c6503636f6d00" .. "00010001" .. "c00c" .. "00010001" .. "00000e10" .. "0004" .. "5db8d822")
local dns_loop_pointer = hex2bin("000101000001000000000000" .. "c00c" .. "00010001")
local dns_truncated_label = hex2bin("000101000001000000000000" .. "056162")
test("parse_header extracts id", function()
  local header, _ = dns.parse_header(dns_query, 1, false)
  assert(header ~= nil, "parse_header should not return nil")
  return assert(header.id == 0x1234, "id should be 0x1234, got " .. tostring(header.id))
end)
test("parse_header extracts qdcount", function()
  local header, _ = dns.parse_header(dns_query, 1, false)
  return assert(header.qdcount == 1, "qdcount should be 1, got " .. tostring(header.qdcount))
end)
test("header rd flag is set", function()
  local header, _ = dns.parse_header(dns_query, 1, false)
  return assert(header.rd == true, "rd flag should be true")
end)
test("header qr flag is false for query", function()
  local header, _ = dns.parse_header(dns_query, 1, false)
  return assert(header.qr == false, "qr should be false for a query")
end)
test("parse returns question name", function()
  local msg, _ = dns.parse(dns_query, 1, false)
  assert(msg ~= nil, "parse should not return nil")
  assert(msg.question ~= nil, "question should not be nil")
  return assert(msg.question.name == "example.com", "question name should be 'example.com', got '" .. tostring(msg.question.name) .. "'")
end)
test("question qtype is A", function()
  local msg, _ = dns.parse(dns_query, 1, false)
  return assert(dns.types[msg.question.qtype] == "A", "qtype should be A, got '" .. tostring(dns.types[msg.question.qtype]) .. "'")
end)
test("question qclass is IN", function()
  local msg, _ = dns.parse(dns_query, 1, false)
  return assert(dns.classes[msg.question.qclass] == "IN", "qclass should be IN, got '" .. tostring(dns.classes[msg.question.qclass]) .. "'")
end)
test("parse response: header qr flag is true", function()
  local msg, _ = dns.parse(dns_response, 1, false)
  return assert(msg.header.qr == true, "qr should be true for a response")
end)
test("parse response: header ra flag is true", function()
  local msg, _ = dns.parse(dns_response, 1, false)
  return assert(msg.header.ra == true, "ra flag should be true")
end)
test("parse response: ancount == 1", function()
  local msg, _ = dns.parse(dns_response, 1, false)
  return assert(msg.header.ancount == 1, "ancount should be 1, got " .. tostring(msg.header.ancount))
end)
test("label compression: answer name is example.com", function()
  local msg, _ = dns.parse(dns_response, 1, false)
  assert(#msg.answers >= 1, "should have at least 1 answer")
  return assert(msg.answers[1].name == "example.com", "answer name should be 'example.com', got '" .. tostring(msg.answers[1].name) .. "'")
end)
test("answer rtype is A", function()
  local msg, _ = dns.parse(dns_response, 1, false)
  return assert(dns.types[msg.answers[1].rtype] == "A", "answer rtype should be A")
end)
test("answer rclass is IN", function()
  local msg, _ = dns.parse(dns_response, 1, false)
  return assert(dns.classes[msg.answers[1].rclass] == "IN", "answer rclass should be IN")
end)
test("answer ttl is 3600", function()
  local msg, _ = dns.parse(dns_response, 1, false)
  return assert(msg.answers[1].ttl == 3600, "ttl should be 3600, got " .. tostring(msg.answers[1].ttl))
end)
test("answer rdata is 93.184.216.34", function()
  local msg, _ = dns.parse(dns_response, 1, false)
  return assert(msg.answers[1].rdata == "\093\184\216\034", "rdata mismatch")
end)
test("types bidirectional: types[1] == 'A'", function()
  return assert(dns.types[1] == "A", "types[1] should be 'A', got '" .. tostring(dns.types[1]) .. "'")
end)
test("types bidirectional: types['A'] == 1", function()
  return assert(dns.types["A"] == 1, "types['A'] should be 1, got " .. tostring(dns.types['A']))
end)
test("classes bidirectional: classes[1] == 'IN'", function()
  return assert(dns.classes[1] == "IN", "classes[1] should be 'IN', got '" .. tostring(dns.classes[1]) .. "'")
end)
test("classes bidirectional: classes['IN'] == 1", function()
  return assert(dns.classes["IN"] == 1, "classes['IN'] should be 1, got " .. tostring(dns.classes['IN']))
end)
test("parse fails safely on compression pointer loop", function()
  local msg, _, err = dns.parse(dns_loop_pointer, 1, false)
  assert(msg == nil, "expected parse failure")
  return assert(err and err:match("loop"), "expected pointer loop error, got " .. tostring(err))
end)
test("parse fails safely on truncated label", function()
  local msg, _, err = dns.parse(dns_truncated_label, 1, false)
  assert(msg == nil, "expected parse failure")
  return assert(err and err:match("truncated DNS label"), "expected truncated label error, got " .. tostring(err))
end)
local dns_response_2a_opt = hex2bin("abcd81800001000200000001" .. "076578616d706c6503636f6d00" .. "00010001" .. "c00c000100010000012c00045db8d822" .. "c00c000100010000012c00045db8d823" .. "0000291000000000000000")
local dns_response_sections = hex2bin("123481800001000100010001" .. "076578616d706c6503636f6d00" .. "00010001" .. "c00c000100010000003c000401020304" .. "c00c000200010000003c0011" .. "036e7331076578616d706c6503636f6d00" .. "c00c000100010000003c000405060708")
local dns_long_name_query = hex2bin("000101000001000000000000" .. "03777777076578616d706c6509737562646f6d61696e0474657374056c6f63616c00" .. "00010001")
local dns_long_name_answer = hex2bin("000181800001000100000000" .. "03777777076578616d706c6509737562646f6d61696e0474657374056c6f63616c00" .. "00010001" .. "c00c000100010000003c000401020304")
local dns_tcp_query = hex2bin("001d" .. "123401000001000000000000076578616d706c6503636f6d0000010001")
test("byte-exact round-trip: two A answers + EDNS OPT", function()
  return assert(tostring(dns.parse(dns_response_2a_opt, 1)) == dns_response_2a_opt)
end)
test("byte-exact round-trip: simple query", function()
  return assert(tostring(dns.parse(dns_query, 1)) == dns_query)
end)
test("byte-exact round-trip: authority and additional sections", function()
  return assert(tostring(dns.parse(dns_response_sections, 1)) == dns_response_sections)
end)
test("byte-exact round-trip: TCP message with size prefix", function()
  return assert(tostring(dns.parse(dns_tcp_query, 1, true)) == dns_tcp_query)
end)
test("byte-exact round-trip: long uncompressed name", function()
  return assert(tostring(dns.parse(dns_long_name_query, 1)) == dns_long_name_query)
end)
test("long uncompressed name decodes all labels", function()
  local msg, _ = dns.parse(dns_long_name_query, 1, false)
  return assert(msg.question.name == "www.example.subdomain.test.local", "got '" .. tostring(msg.question.name) .. "'")
end)
test("compression pointer answer decodes full name", function()
  local msg, _ = dns.parse(dns_long_name_answer, 1, false)
  return assert(msg.answers[1].name == "www.example.subdomain.test.local", "got '" .. tostring(msg.answers[1].name) .. "'")
end)
test("header accessors return numeric opcode, z and rcode", function()
  local h = dns.new_header({ })
  h.opcode = 5
  h.z = 2
  h.rcode = 3
  assert(h.opcode == 5, "opcode should be 5, got " .. tostring(h.opcode))
  assert(h.z == 2, "z should be 2, got " .. tostring(h.z))
  assert(h.rcode == 3, "rcode should be 3, got " .. tostring(h.rcode))
  h.qr = true
  return assert(h.qr == true, "qr should stay boolean")
end)
test("header ra accessor is writable", function()
  local h = dns.new_header({
    ra = true
  })
  assert(h.ra == true, "ra should be true")
  assert(h.ra_z_rcode == 0x80, "ra bit should be 0x80, got " .. tostring(h.ra_z_rcode))
  h.ra = false
  assert(h.ra == false, "ra should be false")
  return assert(h.ra_z_rcode == 0, "ra bit should be cleared, got " .. tostring(h.ra_z_rcode))
end)
test("header stores unknown fields instead of dropping them", function()
  local h = dns.new_header({
    size = 40
  })
  return assert(rawget(h, "size") == 40, "size should be stored, got " .. tostring(rawget(h, 'size')))
end)
test("pack emits size prefix when size is preset", function()
  local msg = dns.new({
    header = dns.new_header({
      size = 0
    })
  })
  local packed = tostring(msg)
  assert(#packed == 14, "packed length should be 14, got " .. tostring(#packed))
  return assert(packed:sub(1, 2) == "\000\012", "prefix should be 12")
end)
test("unknown EDNS option round-trips byte-exact", function()
  local raw = "\000\010\000\002hi"
  local o = dns.parse_opt(raw)
  assert(o.data ~= nil, "unknown option data should not be nil")
  return assert(tostring(o) == raw, "unknown option should round-trip")
end)
test("EDNS client_subnet round-trips byte-exact", function()
  local raw = "\000\008\000\007\000\001\024\000\192\168\001"
  local o = dns.parse_opt(raw)
  assert(o.data.subnet == "\192\168\001", "subnet should be preserved")
  return assert(tostring(o) == raw, "client_subnet option should round-trip")
end)
test("EDNS client_subnet reflects modified fields", function()
  local o = dns.parse_opt("\000\008\000\007\000\001\024\000\192\168\001")
  o.data.source_netmask = 16
  return assert(tostring(o) == "\000\008\000\007\000\001\016\000\192\168\001", "modified source_netmask should be packed")
end)
test("classes NONE and ANY use RFC values", function()
  assert(dns.classes.NONE == 254, "NONE should be 254, got " .. tostring(dns.classes.NONE))
  assert(dns.classes.ANY == 255, "ANY should be 255, got " .. tostring(dns.classes.ANY))
  return assert(dns.classes[1] == "IN", "classes[1] should be 'IN'")
end)
test("parse_opt reuses module-level data metatables", function()
  local a = dns.parse_opt("\000\010\000\002hi")
  local b = dns.parse_opt("\000\010\000\002ho")
  assert(getmetatable(a.data) == getmetatable(b.data), "unknown options should share one metatable")
  local c = dns.parse_opt("\000\008\000\007\000\001\024\000\192\168\001")
  local d = dns.parse_opt("\000\008\000\007\000\001\024\000\192\168\002")
  return assert(getmetatable(c.data) == getmetatable(d.data), "client_subnet options should share one metatable")
end)
return util.summary("l7/dns")
