local util = require("ipparse.lib.util")
local test
test = util.test
local ext = require("ipparse.l7.tls.handshake.extension")
local sn = require("ipparse.l7.tls.handshake.extension.server_name")
local sv = require("ipparse.l7.tls.handshake.extension.supported_versions")
local sp = require("ipparse.lib.pack_compat").pack
test("extension: parse round-trips pack", function()
  local raw = sp(">H s2", 0x0000, "abc")
  local e, off = ext.parse(raw, 1)
  assert(e and e.type == 0 and e.data == "abc", "extension parse failed")
  assert(off == #raw + 1, "offset should be past the extension")
  return assert(tostring(e) == raw, "pack should round-trip")
end)
test("extension: truncated header returns nil", function()
  local e, off = ext.parse("\000", 1)
  return assert(e == nil and off == 1, "should return nil, input offset")
end)
test("extension: truncated data returns nil", function()
  local raw = sp(">HH", 0x0000, 10)
  local e, off = ext.parse(raw, 1)
  return assert(e == nil and off == 1, "should return nil on short data")
end)
local sn_entry = sp(">B s2", 0, "example.com")
local sn_raw = sp(">H", #sn_entry) .. sn_entry
test("server_name: parses single host_name", function()
  local s = sn.parse(sn_raw, 1)
  assert(s and s.name == "example.com", "expected example.com, got " .. tostring(s and s.name))
  return assert(not s.incomplete, "should be complete")
end)
test("server_name: truncated list returns nil with error", function()
  local s, off, err = sn.parse("\000", 1)
  return assert(s == nil and err, "should return nil, off, err")
end)
test("server_name: truncated entry flagged incomplete", function()
  local bad = sp(">H", 20) .. "\000\000\016ab"
  local s = sn.parse(bad, 1)
  return assert(s and s.incomplete, "should be flagged incomplete")
end)
test("supported_versions: ServerHello selected version", function()
  local v = sv.parse(sp(">H", 0x0304), 1)
  return assert(v and v.selected == 0x0304, "expected selected TLS 1.3")
end)
test("supported_versions: ClientHello list", function()
  local raw = sp(">B HH", 4, 0x0304, 0x0303)
  local v, off = sv.parse(raw, 1)
  assert(v and v.versions and #v.versions == 2, "expected 2 versions")
  assert(v.versions[1] == 0x0304 and v.versions[2] == 0x0303, "version values mismatch")
  return assert(off == #raw + 1, "offset should be past the list")
end)
test("supported_versions: truncated list returns nil", function()
  local v, off = sv.parse(sp(">B H", 8, 0x0304), 1)
  return assert(v == nil and off == 1, "should return nil on truncated list")
end)
test("supported_versions: empty data returns nil", function()
  local v = sv.parse("", 1)
  return assert(v == nil, "should return nil on empty data")
end)
return util.summary("l7/tls/handshake")
