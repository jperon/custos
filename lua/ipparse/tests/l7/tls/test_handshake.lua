local util = require("ipparse.lib.util")
local test
test = util.test
local ext = require("ipparse.l7.tls.handshake.extension")
local sn = require("ipparse.l7.tls.handshake.extension.server_name")
local sv = require("ipparse.l7.tls.handshake.extension.supported_versions")
local hs = require("ipparse.l7.tls.handshake")
local sp = require("ipparse.lib.pack_compat").pack
test("extension: parse round-trips pack", function()
  local raw = sp(">H s2", 0x0000, "abc")
  local e, off = ext.parse(raw, 1)
  assert(e and e.type == 0 and e.data == "abc", "extension parse failed")
  assert(off == #raw + 1, "offset should be past the extension")
  return assert(tostring(e) == raw, "pack should round-trip")
end)
test("extension: truncated header returns nil", function()
  local e, off = ext.parse("\000", 1)
  return assert(e == nil and off == 1, "should return nil, input offset")
end)
test("extension: truncated data returns nil", function()
  local raw = sp(">HH", 0x0000, 10)
  local e, off = ext.parse(raw, 1)
  return assert(e == nil and off == 1, "should return nil on short data")
end)
local sn_entry = sp(">B s2", 0, "example.com")
local sn_raw = sp(">H", #sn_entry) .. sn_entry
test("server_name: parses single host_name", function()
  local s = sn.parse(sn_raw, 1)
  assert(s and s.name == "example.com", "expected example.com, got " .. tostring(s and s.name))
  return assert(not s.incomplete, "should be complete")
end)
test("server_name: truncated list returns nil with error", function()
  local s, off, err = sn.parse("\000", 1)
  return assert(s == nil and err, "should return nil, off, err")
end)
test("server_name: truncated entry flagged incomplete", function()
  local bad = sp(">H", 20) .. "\000\000\016ab"
  local s = sn.parse(bad, 1)
  return assert(s and s.incomplete, "should be flagged incomplete")
end)
test("supported_versions: ServerHello selected version", function()
  local v = sv.parse(sp(">H", 0x0304), 1)
  return assert(v and v.selected == 0x0304, "expected selected TLS 1.3")
end)
test("supported_versions: ClientHello list", function()
  local raw = sp(">B HH", 4, 0x0304, 0x0303)
  local v, off = sv.parse(raw, 1)
  assert(v and v.versions and #v.versions == 2, "expected 2 versions")
  assert(v.versions[1] == 0x0304 and v.versions[2] == 0x0303, "version values mismatch")
  return assert(off == #raw + 1, "offset should be past the list")
end)
test("supported_versions: truncated list returns nil", function()
  local v, off = sv.parse(sp(">B H", 8, 0x0304), 1)
  return assert(v == nil and off == 1, "should return nil on truncated list")
end)
test("supported_versions: empty data returns nil", function()
  local v = sv.parse("", 1)
  return assert(v == nil, "should return nil on empty data")
end)
test("handshake: message_types matches the IANA registry", function()
  assert(hs.message_types.finished == 20, "finished should be 20")
  assert(hs.message_types[24] == "key_update", "[24] should be key_update")
  assert(hs.message_types.encrypted_extensions == 8, "encrypted_extensions should be 8")
  return assert(hs.message_types[1] == "client_hello", "[1] should be client_hello")
end)
local tls = require("ipparse.l7.tls")
test("handshake: pack round-trips a 3-byte length", function()
  local raw = hs.pack({
    type = 1,
    len = 0x12345
  })
  assert(#raw == 4, "expected 4-byte header, got " .. tostring(#raw))
  local h, off = hs.parse(raw, 1)
  assert(h and h.type == 1, "type mismatch")
  assert(h.len == 0x12345, "expected len 0x12345, got " .. tostring(h.len))
  assert(off == 5, "offset should be past the header")
  return assert(tostring(h) == raw, "tostring should repack identically")
end)
test("handshake: parse_ciphers returns every 16-bit value", function()
  local raw = sp(">HHH", 0x1301, 0x1302, 0xc02f)
  local c = hs.parse_ciphers(raw)
  assert(#c == 3, "expected 3 ciphers, got " .. tostring(#c))
  return assert(c[1] == 0x1301 and c[3] == 0xc02f, "cipher values mismatch")
end)
test("handshake: parse_compressions returns every byte", function()
  local c = hs.parse_compressions("\000\001\002")
  assert(#c == 3, "expected 3 compressions, got " .. tostring(#c))
  return assert(c[1] == 0 and c[3] == 2, "compression values mismatch")
end)
test("handshake: iter_extensions walks every extension", function()
  local raw = sp(">H s2", 0x0000, "abc") .. sp(">H s2", 0x002b, "de")
  local types = { }
  for e in hs.iter_extensions(raw) do
    types[#types + 1] = e.type
  end
  assert(#types == 2, "expected 2 extensions, got " .. tostring(#types))
  return assert(types[1] == 0 and types[2] == 0x002b, "extension types mismatch")
end)
test("handshake: iter_extensions honours an explicit offset and length", function()
  local raw = sp(">H s2", 0x0000, "abc") .. sp(">H s2", 0x002b, "de")
  local second = sp(">H s2", 0x002b, "de")
  local types = { }
  for e in hs.iter_extensions(raw, #raw - #second + 1, #second) do
    types[#types + 1] = e.type
  end
  return assert(#types == 1 and types[1] == 0x002b, "expected only the second extension")
end)
test("tls: record header pack round-trips", function()
  local raw = tls.pack({
    type = 0x16,
    ver = 3,
    subver = 3,
    len = 4
  })
  assert(#raw == 5, "expected 5-byte header, got " .. tostring(#raw))
  local r, off = tls.parse(raw, 1)
  assert(r and r.type == 0x16, "type mismatch")
  assert(r.ver == 3 and r.subver == 3, "version mismatch")
  assert(r.len == 4, "expected len 4")
  assert(r.data_off == 6, "data offset should be past the header")
  return assert(tostring(r) == raw, "tostring should repack identically")
end)
test("server_name: parse_entry honours the default offset", function()
  local raw = sp(">B s2", 0, "example.org")
  local e, off = sn.parse_entry(raw)
  assert(e and e.type == 0 and e.name == "example.org", "entry mismatch")
  assert(off == #raw + 1, "offset should be past the entry")
  return assert(sn.pack_entry(e) == raw, "pack_entry should round-trip")
end)
test("server_name: pack round-trips a parsed list", function()
  local s = sn.parse(sn_raw, 1)
  return assert(sn.pack(s) == sn_raw, "pack should reproduce the list bytes")
end)
test("server_name: empty name list packs to a zero length", function()
  return assert(sn.pack({ }) == "\000\000", "empty list should pack as 0x0000")
end)
test("supported_versions: list of three versions round-trips", function()
  local raw = sp(">B HHH", 6, 0x0304, 0x0303, 0x0301)
  local v, off = sv.parse(raw, 1)
  assert(v and #v.versions == 3, "expected 3 versions")
  assert(v.versions[1] == 0x0304 and v.versions[3] == 0x0301, "version values mismatch")
  assert(off == #raw + 1, "offset should be past the list")
  return assert(tostring(v) == raw, "tostring should repack the list identically")
end)
test("supported_versions: selected version round-trips", function()
  local raw = sp(">H", 0x0304)
  local v = sv.parse(raw, 1)
  return assert(tostring(v) == raw, "tostring should repack the selected version")
end)
return util.summary("l7/tls/handshake")
