local util = require("ipparse.lib.util")
local test
test = util.test
local ip4 = require("ipparse.l3.ip4")
local frag = require("ipparse.l3.fragmented_ip4")
local src = ip4.s2ip4("1.2.3.4")
local dst = ip4.s2ip4("5.6.7.8")
local build
build = function(id, ff, data)
  local raw = ip4.pack(ip4.new({
    src = src,
    dst = dst,
    protocol = 17,
    id = id,
    ff = ff,
    data = data
  }))
  local ip = ip4.parse(raw, 1)
  return raw, ip
end
test("non-fragmented packet is returned immediately", function()
  frag.reset()
  local raw, ip = build(1, 0, "hello")
  local payload, header = frag.collect(ip, raw)
  assert(payload == "hello", "expected 'hello', got '" .. tostring(payload) .. "'")
  return assert(header == ip, "expected the original header")
end)
test("two fragments in order are reassembled", function()
  frag.reset()
  local raw1, ip1 = build(2, 0x2000, "ABCDEFGH")
  local raw2, ip2 = build(2, 1, "IJKL")
  local pending = frag.collect(ip1, raw1)
  assert(pending == nil, "first fragment should be pending")
  local payload, header = frag.collect(ip2, raw2)
  assert(payload == "ABCDEFGHIJKL", "expected 'ABCDEFGHIJKL', got '" .. tostring(payload) .. "'")
  return assert(header == ip1, "header should be the first fragment's header")
end)
test("three fragments out of order (last first)", function()
  frag.reset()
  local raw1, ip1 = build(3, 0x2000, "01234567")
  local raw2, ip2 = build(3, 0x2001, "89abcdef")
  local raw3, ip3 = build(3, 2, "ghij")
  assert(frag.collect(ip3, raw3) == nil, "last fragment alone should be pending")
  assert(frag.collect(ip2, raw2) == nil, "middle fragment alone should be pending")
  local payload, header = frag.collect(ip1, raw1)
  assert(payload == "0123456789abcdefghij", "got '" .. tostring(payload) .. "'")
  return assert(header == ip1, "header should be the first fragment's header")
end)
test("hole in the middle keeps the flow pending", function()
  frag.reset()
  local raw1, ip1 = build(4, 0x2000, "ABCDEFGH")
  local raw3, ip3 = build(4, 2, "WXYZ")
  assert(frag.collect(ip1, raw1) == nil, "first fragment should be pending")
  return assert(frag.collect(ip3, raw3) == nil, "a hole must not complete the flow")
end)
test("duplicate fragment is tolerated", function()
  frag.reset()
  local raw1, ip1 = build(5, 0x2000, "ABCDEFGH")
  local raw2, ip2 = build(5, 1, "IJKL")
  assert(frag.collect(ip1, raw1) == nil, "first fragment should be pending")
  assert(frag.collect(ip1, raw1) == nil, "duplicate first fragment should stay pending")
  local payload, header = frag.collect(ip2, raw2)
  assert(payload == "ABCDEFGHIJKL", "got '" .. tostring(payload) .. "'")
  return assert(header == ip1, "header should be the first fragment's header")
end)
test("two interleaved flows are kept separate", function()
  frag.reset()
  local a1raw, a1 = build(10, 0x2000, "AAAAAAAA")
  local a2raw, a2 = build(10, 1, "aaaa")
  local b1raw, b1 = build(11, 0x2000, "BBBBBBBB")
  local b2raw, b2 = build(11, 1, "bbbb")
  assert(frag.collect(a1, a1raw) == nil, "A first should be pending")
  assert(frag.collect(b1, b1raw) == nil, "B first should be pending")
  local payload_a, header_a = frag.collect(a2, a2raw)
  assert(payload_a == "AAAAAAAAaaaa", "got '" .. tostring(payload_a) .. "'")
  assert(header_a == a1, "A header should be the first fragment's header")
  local payload_b, header_b = frag.collect(b2, b2raw)
  assert(payload_b == "BBBBBBBBbbbb", "got '" .. tostring(payload_b) .. "'")
  return assert(header_b == b1, "B header should be the first fragment's header")
end)
test("MF fragment length not a multiple of 8 is rejected", function()
  frag.reset()
  local raw, ip = build(20, 0x2000, "ABCDE")
  local res, err = frag.collect(ip, raw)
  assert(res == nil, "expected nil result")
  return assert(err == "invalid fragment length", "got '" .. tostring(err) .. "'")
end)
test("fragment exceeding 65535 bytes is rejected", function()
  frag.reset()
  local raw, ip = build(30, 0x2000 + 8191, "ABCDEFGH")
  local res, err = frag.collect(ip, raw)
  assert(res == nil, "expected nil result")
  return assert(err == "fragment exceeds 65535 bytes", "got '" .. tostring(err) .. "'")
end)
test("oldest pending flow is evicted beyond MAX_PENDING", function()
  frag.reset()
  local first_raw, first_ip = nil, nil
  local last_raw, last_ip = nil, nil
  for i = 1, 65 do
    local raw, ip = build(i, 0x2000, "ABCDEFGH")
    frag.collect(ip, raw)
    if i == 1 then
      first_raw, first_ip = raw, ip
    end
    if i == 65 then
      last_raw, last_ip = raw, ip
    end
  end
  local raw2, ip2 = build(1, 1, "WXYZ")
  local evicted = frag.collect(ip2, raw2)
  assert(evicted == nil, "evicted flow must not complete")
  local raw3, ip3 = build(65, 1, "WXYZ")
  local payload, header = frag.collect(ip3, raw3)
  assert(payload == "ABCDEFGHWXYZ", "got '" .. tostring(payload) .. "'")
  return assert(header == last_ip, "header should be the last flow's first fragment")
end)
test("truncated packet is rejected", function()
  frag.reset()
  local raw, ip = build(40, 0, "hello")
  local short = raw:sub(1, #raw - 1)
  local res, err = frag.collect(ip, short)
  assert(res == nil, "expected nil result")
  return assert(err == "truncated packet", "got '" .. tostring(err) .. "'")
end)
test("completed flows do not grow the eviction queue", function()
  frag.reset()
  for i = 1, 1000 do
    local raw1, ip1 = build(i, 0x2000, "ABCDEFGH")
    local raw2, ip2 = build(i, 1, "IJKL")
    assert(frag.collect(ip1, raw1) == nil, "flow " .. tostring(i) .. " first fragment should be pending")
    local payload = frag.collect(ip2, raw2)
    assert(payload == "ABCDEFGHIJKL", "flow " .. tostring(i) .. " should complete, got '" .. tostring(payload) .. "'")
  end
  local pending, queued = frag.stats()
  assert(pending == 0, "pending should be 0, got " .. tostring(pending))
  return assert(queued == 0, "eviction queue should be empty, got " .. tostring(queued))
end)
test("eviction queue holds one entry per incomplete flow", function()
  frag.reset()
  for i = 1, 10 do
    local raw, ip = build(i, 0x2000, "ABCDEFGH")
    assert(frag.collect(ip, raw) == nil, "flow " .. tostring(i) .. " should be pending")
  end
  local pending, queued = frag.stats()
  assert(pending == 10, "pending should be 10, got " .. tostring(pending))
  return assert(queued == 10, "eviction queue should hold 10 entries, got " .. tostring(queued))
end)
test("reused key evicts the oldest living flow, not a newer one", function()
  frag.reset()
  local a1raw, a1 = build(7, 0x2000, "AAAAAAAA")
  assert(frag.collect(a1, a1raw) == nil, "A first should be pending")
  local a2raw, a2 = build(7, 1, "aaaa")
  local payload = frag.collect(a2, a2raw)
  assert(payload == "AAAAAAAAaaaa", "A should complete, got '" .. tostring(payload) .. "'")
  local n1raw, n1 = build(7, 0x2000, "BBBBBBBB")
  assert(frag.collect(n1, n1raw) == nil, "new id 7 flow should be pending")
  for i = 100, 162 do
    local raw, ip = build(i, 0x2000, "CCCCCCCC")
    assert(frag.collect(ip, raw) == nil, "flow " .. tostring(i) .. " should be pending")
  end
  local pending, queued = frag.stats()
  assert(pending == 64, "pending should be 64, got " .. tostring(pending))
  assert(queued == 64, "eviction queue should hold 64 entries, got " .. tostring(queued))
  local raw, ip = build(200, 0x2000, "DDDDDDDD")
  assert(frag.collect(ip, raw) == nil, "65th flow should be pending")
  pending, queued = frag.stats()
  assert(pending == 64, "pending should stay at 64, got " .. tostring(pending))
  assert(queued == 64, "eviction queue should hold 64 entries, got " .. tostring(queued))
  local r200raw, r200 = build(200, 1, "dddd")
  payload = frag.collect(r200, r200raw)
  assert(payload == "DDDDDDDDdddd", "newest flow should survive, got '" .. tostring(payload) .. "'")
  local n2raw, n2 = build(7, 1, "bbbb")
  assert(frag.collect(n2, n2raw) == nil, "oldest living flow (id 7) must have been evicted")
  local r100raw, r100 = build(100, 1, "cccc")
  payload = frag.collect(r100, r100raw)
  assert(payload == "CCCCCCCCcccc", "a recent flow should survive, got '" .. tostring(payload) .. "'")
  local r150raw, r150 = build(150, 1, "eeee")
  payload = frag.collect(r150, r150raw)
  return assert(payload == "CCCCCCCCeeee", "another recent flow should survive, got '" .. tostring(payload) .. "'")
end)
return util.summary("l3/fragmented_ip4")
