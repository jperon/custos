local util = require("ipparse.lib.util")
local test
test = util.test
local bin2hex, hex2bin, filterascii, hexdump, lbin2hex, dump, need_bytes
do
  local _obj_0 = require("ipparse.init")
  bin2hex, hex2bin, filterascii, hexdump, lbin2hex, dump, need_bytes = _obj_0.bin2hex, _obj_0.hex2bin, _obj_0.filterascii, _obj_0.hexdump, _obj_0.lbin2hex, _obj_0.dump, _obj_0.need_bytes
end
test("bin2hex converts bytes to hex", function()
  return assert(bin2hex("\255\000\171") == "ff00ab", "bin2hex failed")
end)
test("hex2bin converts hex to bytes", function()
  local result = hex2bin("ff00")
  return assert(result == "\255\000", "hex2bin failed")
end)
test("hex2bin single byte", function()
  local result = hex2bin("ab")
  return assert(result == "\171", "hex2bin single byte failed")
end)
test("hex2bin returns exactly one value", function()
  local n = select("#", hex2bin("00ff"))
  return assert(n == 1, "expected 1 return value, got " .. tostring(n))
end)
test("filterascii replaces non-printable with dot", function()
  local result = filterascii("\001hello\255")
  return assert(result == ".hello.", "expected '.hello.', got '" .. tostring(result) .. "'")
end)
test("filterascii keeps printable chars", function()
  local result = filterascii("hello")
  return assert(result == "hello", "expected 'hello', got '" .. tostring(result) .. "'")
end)
test("lbin2hex handles a 100-byte string", function()
  local result = lbin2hex(string.rep("a", 100))
  return assert(#result == 200, "expected 200 hex chars, got " .. tostring(#result))
end)
test("lbin2hex handles a 128-byte string", function()
  local result = lbin2hex(string.rep("a", 128))
  return assert(#result == 256, "expected 256 hex chars, got " .. tostring(#result))
end)
test("lbin2hex handles a 200-byte string", function()
  local result = lbin2hex(string.rep("a", 200))
  return assert(#result == 400, "expected 400 hex chars, got " .. tostring(#result))
end)
test("lbin2hex handles the empty string", function()
  local result = lbin2hex("")
  return assert(result == "", "expected '', got '" .. tostring(result) .. "'")
end)
test("bin2hex handles a 4096-byte string", function()
  local result = bin2hex(string.rep("a", 4096))
  assert(#result == 8192, "expected 8192 hex chars, got " .. tostring(#result))
  return assert(result == string.rep("61", 4096), "bin2hex content mismatch")
end)
test("bin2hex converts non-printable bytes", function()
  local result = bin2hex("\000\010\255")
  return assert(result == "000aff", "expected '000aff', got '" .. tostring(result) .. "'")
end)
test("hexdump prints offset and hex for a 16-byte line", function()
  local result = hexdump("abcdefghijklmnop", 1, 8, 2)
  assert(result:sub(1, 6) == "0000: ", "expected '0000: ' prefix, got '" .. tostring(result:sub(1, 6)) .. "'")
  return assert(result:find("6162636465666768", 1, true), "expected hex of first bytes in '" .. tostring(result) .. "'")
end)
test("dump renders sorted key/value pairs", function()
  assert(dump({
    b = 2,
    a = 1
  }) == "a: 1, b: 2", "dump mismatch")
  return assert(dump({ }) == "", "empty table should dump as an empty string")
end)
test("need_bytes rejects negative length and bad offset", function()
  assert(need_bytes("abc", 1, 0) == true, "zero length at valid offset should pass")
  assert(need_bytes("abc", 0, 1) == false, "offset below 1 should fail")
  assert(need_bytes("abc", 1, -1) == false, "negative length should fail")
  return assert(need_bytes("abc", 4, 1) == false, "offset past the end should fail")
end)
test("hexdump keeps complete line output unchanged", function()
  local result = hexdump("abcdefghijklmnop")
  return assert(result == "0000: 6162636465666768 696a6b6c6d6e6f70 abcdefghijklmnop", "complete line changed: '" .. tostring(result) .. "'")
end)
test("hexdump keeps two complete lines unchanged", function()
  local result = hexdump("abcdefghijklmnopqrstuvwxyz012345")
  local expected = "0000: 6162636465666768 696a6b6c6d6e6f70 abcdefghijklmnop\n0010: 7172737475767778 797a303132333435 qrstuvwxyz012345"
  return assert(result == expected, "complete lines changed: '" .. tostring(result) .. "'")
end)
test("hexdump keeps complete non-default line unchanged", function()
  local result = hexdump("abcdefghijkl", 1, 4, 3)
  return assert(result == "0000: 61626364 65666768 696a6b6c abcdefghijkl", "non-default complete line changed: '" .. tostring(result) .. "'")
end)
test("hexdump pads an incomplete final line", function()
  local result = hexdump("abc")
  local expected = "0000: 616263" .. string.rep(" ", 27) .. " abc"
  return assert(result == expected, "unexpected incomplete line: '" .. tostring(result) .. "'")
end)
test("hexdump honours offset, length, cols and format", function()
  local result = hexdump("\001\002\003\004", 2, 2, 1, "%02X")
  return assert(result == "0001: 0203 ..\n0003: 04   .", "unexpected hexdump: '" .. tostring(result) .. "'")
end)
test("hexdump aligns ascii on 20 bytes", function()
  local result = hexdump("abcdefghijklmnopqrst")
  local first, second = result:match("([^\n]*)\n([^\n]*)")
  local a = first:find("abcdefghijklmnop", 1, true)
  local b = second:find("qrst", 1, true)
  return assert(a and b and a == b, "ascii columns differ: " .. tostring(a) .. " vs " .. tostring(b) .. " in '" .. tostring(result) .. "'")
end)
test("hexdump aligns a single byte", function()
  local result = hexdump("a")
  assert(result:find("a", 1, true) == 41, "ascii should start at column 41: '" .. tostring(result) .. "'")
  return assert(result:sub(-1) ~= " ", "line must not end with a space: '" .. tostring(result) .. "'")
end)
test("hexdump aligns 17 bytes", function()
  local result = hexdump("abcdefghijklmnopq")
  local first, second = result:match("([^\n]*)\n([^\n]*)")
  local a = first:find("abcdefghijklmnop", 1, true)
  local b = second:find("q", 1, true)
  assert(a and b and a == b, "ascii columns differ: " .. tostring(a) .. " vs " .. tostring(b) .. " in '" .. tostring(result) .. "'")
  return assert(second:sub(-1) ~= " ", "line must not end with a space: '" .. tostring(second) .. "'")
end)
test("hexdump aligns ascii with non-default length and cols", function()
  local result = hexdump("abcdefghij", 1, 4, 3)
  local expected = "0000: 61626364 65666768 696a     abcdefghij"
  assert(result == expected, "unexpected padded line: '" .. tostring(result) .. "'")
  return assert(result:sub(-1) ~= " ", "line must not end with a space: '" .. tostring(result) .. "'")
end)
test("hexdump never pads trailing spaces on incomplete lines", function()
  for _, s in ipairs({
    "a",
    "abc",
    "abcdefghijklmnopq",
    "abcdefghijklmnopqrst"
  }) do
    local result = hexdump(s)
    for line in result:gmatch("[^\n]+") do
      assert(line:sub(-1) ~= " ", "line ends with a space: '" .. tostring(line) .. "'")
    end
  end
end)
return util.summary("init")
